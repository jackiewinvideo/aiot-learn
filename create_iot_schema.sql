CREATE TABLE IF NOT EXISTS sensors (
    sensor_id VARCHAR(50) PRIMARY KEY,
    sensor_name VARCHAR(100) NOT NULL,
    location VARCHAR(200),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sensor_data (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id VARCHAR(50) NOT NULL REFERENCES sensors(sensor_id),
    temperature NUMERIC(5, 2) NOT NULL,
    humidity NUMERIC(5, 2) NOT NULL CHECK (humidity BETWEEN 0 AND 100),
    timestamp TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_sensor_data_sensor_id
    ON sensor_data(sensor_id);
CREATE INDEX IF NOT EXISTS idx_sensor_data_timestamp
    ON sensor_data(timestamp DESC);

CREATE TABLE IF NOT EXISTS alert_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id VARCHAR(50) NOT NULL REFERENCES sensors(sensor_id),
    rule_name VARCHAR(100) NOT NULL,
    condition_type VARCHAR(50) NOT NULL CHECK (
        condition_type IN (
            'temperature_high',
            'temperature_low',
            'humidity_high',
            'humidity_low'
        )
    ),
    threshold NUMERIC(5, 2) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE OR REPLACE VIEW latest_sensor_data AS
SELECT
    sensors.sensor_id,
    sensors.sensor_name,
    sensors.location,
    latest.temperature,
    latest.humidity,
    latest.timestamp
FROM sensors
LEFT JOIN LATERAL (
    SELECT temperature, humidity, timestamp
    FROM sensor_data
    WHERE sensor_data.sensor_id = sensors.sensor_id
    ORDER BY timestamp DESC
    LIMIT 1
) AS latest ON TRUE;

CREATE OR REPLACE VIEW sensor_statistics AS
SELECT
    sensor_id,
    COUNT(*) AS data_count,
    AVG(temperature) AS avg_temperature,
    MIN(temperature) AS min_temperature,
    MAX(temperature) AS max_temperature,
    AVG(humidity) AS avg_humidity,
    MIN(humidity) AS min_humidity,
    MAX(humidity) AS max_humidity,
    MAX(timestamp) AS last_updated
FROM sensor_data
GROUP BY sensor_id;
